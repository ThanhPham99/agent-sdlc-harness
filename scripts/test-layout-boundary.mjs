// Architecture test: runtime/layout.mjs is the ONLY place that knows how the
// .agent-sdlc tree is shaped.
//
// The layout used to be 24 top-level namespaces created ad hoc by 20+ modules,
// each writing `path.join(stateDir(root),'<literal>')` at the point of use.
// Nothing could enumerate the tree, so nothing could migrate it, document it or
// garbage-collect it -- retention.mjs kept its own list of per-run paths and had
// fallen six behind, silently orphaning every reclaimed run's evidence,
// ci-evidence, delivery, traceability, requirement-update and workspace bytes.
//
// Consolidating that was the fix. Keeping it consolidated is this test's job:
// the next module that needs a path under the state directory must add an
// accessor rather than a string literal, and this fails until it does.
//
// The check is deliberately narrow. A bare `stateDir(root)` is fine -- callers
// legitimately need the root. Naming `.agent-sdlc` in a comment, a schema id, a
// git branch name or a documentation string is fine. What is not fine is
// *composing a sub-path*: joining a literal segment onto the state directory,
// or spelling the state directory and a child out together.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {STATE_DIRNAME} from '../runtime/layout.mjs';
import {writeReport} from './lib/report-io.mjs';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const AUTHORITY='runtime/layout.mjs';
const SCAN_DIRS=['runtime','scripts','evals','adapters','harness','bin','hooks','commands','roles','rules','policies','protocol','types'];
const SKIP_DIRS=new Set(['node_modules','.git','dist',STATE_DIRNAME,'fixtures','release']);
/**
 * The only files allowed to compose a state-directory path by hand, each with
 * the reason it cannot use the authority.
 *
 * An exemption is a liability, so it is a named entry with a justification
 * rather than a pattern: a blanket exemption is how `statusline.mjs` sat on the
 * v1 tree unnoticed. Anything listed here must be covered by a drift assertion
 * elsewhere, because it is duplicated knowledge by construction.
 */
const ALLOWLIST=new Map([
  ['scripts/test-layout-boundary.mjs',
   'this file: the self-check must contain a sample of every pattern to prove the pattern still fires, and a rule that cannot be shown to fail is a rule nobody should trust'],
  ['adapters/hooks/statusline.mjs',
   'dependency-free by contract (runs on every prompt render) and byte-mirrored to hooks/statusline.mjs, so a relative import would resolve from two different directories; scripts/test-layout.mjs asserts its literals still match the layout'],
  ['hooks/statusline.mjs',
   'byte-for-byte mirror of adapters/hooks/statusline.mjs, generated by scripts/gen-activation-assets.mjs']
]);

/**
 * The two ways a sub-path gets composed.
 *
 * `stateDir(x),'seg'`      -- joining onto the accessor's result.
 * `'.agent-sdlc','seg'`    -- spelling the directory and a child out together.
 *
 * Both are matched with the literal quoted segment required, so
 * `path.join(projectRoot, STATE_DIRNAME)` and a bare `stateDir(projectRoot)`
 * pass, as they should.
 */
const escaped=STATE_DIRNAME.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const PATTERNS=[
  {id:'JOIN_ONTO_STATE_DIR',
   // Both a call and a bare identifier. The identifier form is not pedantry:
   // adapters/hooks/statusline.mjs held `const stateDir=path.join(dir,'.agent-sdlc')`
   // and then joined onto it, and the call-only rule scanned that file and
   // reported it clean while it was still reading the v1 tree.
   re:new RegExp(String.raw`stateDir\s*(\([^)]*\))?\s*,\s*['"\`]`),
   why:`a literal segment is joined onto stateDir; add an accessor in ${AUTHORITY} instead`},
  {id:'LITERAL_STATE_DIR_IN_JOIN',
   // The state directory named as ANY argument of a join, not only where a
   // literal child follows it. `path.join(startDir,'.agent-sdlc')` composes the
   // root by hand, which is the step that makes every later hand-join possible.
   re:new RegExp(String.raw`(join|resolve|normalize)\s*\([^)]*['"\`]${escaped}['"\`]`),
   why:`the state directory is composed by hand inside a path call; use stateDir() from ${AUTHORITY}`},
  {id:'LITERAL_STATE_SUBPATH',
   // A join() call is required, because a bare list of directory NAMES --
   // `['.git','node_modules','.agent-sdlc']`, which several walkers use to
   // decide what to skip -- names the directory without composing a path into
   // it, and flagging those taught nothing while making the rule untrustworthy.
   re:new RegExp(String.raw`(join|resolve|normalize)\s*\([^)]*['"\`]${escaped}['"\`]\s*,\s*['"\`]`),
   why:`the state directory and a child are composed as literals; add an accessor in ${AUTHORITY} instead`},
  {id:'LITERAL_STATE_SLASH_SUBPATH',
   re:new RegExp(String.raw`['"\`]${escaped}/[A-Za-z0-9_.-]`),
   why:`a '${STATE_DIRNAME}/<child>' path literal; derive it from ${AUTHORITY} instead`}
];

/** Lines that name a path but are not composing one. */
function isExempt(line){
  const t=line.trim();
  if(t.startsWith('//')||t.startsWith('*')||t.startsWith('/*'))return true;
  // `.agent-sdlc/` as a git-status prefix or ignore rule is a string being
  // matched, not a path being built -- but those now go through the layout too,
  // so only a comment is exempt. Keep this function as the single place an
  // exemption could be added, with a reason.
  return false;
}

function walk(dir,out=[]){
  if(!fs.existsSync(dir))return out;
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
    if(entry.isDirectory()){
      if(SKIP_DIRS.has(entry.name))continue;
      walk(path.join(dir,entry.name),out);
    }else if(/\.(mjs|cjs|js)$/.test(entry.name)){
      out.push(path.join(dir,entry.name));
    }
  }
  return out;
}

const violations=[];
let scanned=0;
for(const d of SCAN_DIRS){
  for(const file of walk(path.join(ROOT,d))){
    const relPath=path.relative(ROOT,file).split(path.sep).join('/');
    if(relPath===AUTHORITY||ALLOWLIST.has(relPath))continue;
    scanned++;
    const lines=fs.readFileSync(file,'utf8').split('\n');
    lines.forEach((line,i)=>{
      if(isExempt(line))return;
      for(const p of PATTERNS){
        if(p.re.test(line)){
          violations.push({file:relPath,line:i+1,rule:p.id,why:p.why,source:line.trim().slice(0,160)});
          return;
        }
      }
    });
  }
}

// The test must be able to fail. A pattern that matches nothing anywhere is
// indistinguishable from a pattern that is simply broken, so each one is proved
// against a sample it must catch.
const selfCheck=[
  {rule:'JOIN_ONTO_STATE_DIR',sample:`const p=path.join(stateDir(projectRoot),'runs');`},
  {rule:'JOIN_ONTO_STATE_DIR',sample:`const p=path.join(stateDir,'runs');`},
  {rule:'LITERAL_STATE_DIR_IN_JOIN',sample:`const stateDir=path.join(startDir,'${STATE_DIRNAME}');`},
  {rule:'LITERAL_STATE_DIR_IN_JOIN',sample:`const d=path.resolve(root,'${STATE_DIRNAME}');`},
  {rule:'LITERAL_STATE_SUBPATH',sample:`const p=path.join(root,'${STATE_DIRNAME}','project.json');`},
  // And it must NOT fire on a name list, or the rule is back to over-reaching.
  {rule:'LITERAL_STATE_SLASH_SUBPATH',sample:`if(rel.startsWith('${STATE_DIRNAME}/runs'))return;`}
];
const mustNotMatch=[
  {rule:'LITERAL_STATE_SUBPATH',sample:`const skipDirs=new Set(['.git','node_modules','${STATE_DIRNAME}','.claude']);`},
  {rule:'JOIN_ONTO_STATE_DIR',sample:`const d=stateDir(projectRoot);`}
];
const selfCheckFailures=[];
for(const c of selfCheck){
  const pattern=PATTERNS.find(p=>p.id===c.rule);
  if(!pattern||!pattern.re.test(c.sample))
    selfCheckFailures.push({rule:c.rule,error:'the rule does not match the sample it must catch',sample:c.sample});
}
for(const c of mustNotMatch){
  const pattern=PATTERNS.find(p=>p.id===c.rule);
  if(pattern&&pattern.re.test(c.sample))
    selfCheckFailures.push({rule:c.rule,error:'the rule fires on a sample it must ignore',sample:c.sample});
}

const status=violations.length||selfCheckFailures.length?'FAIL':'PASS';
const report={
  schema:'agent-sdlc/eval-report/v1',
  suite:'layout-boundary',
  authority:AUTHORITY,
  scanned_files:scanned,
  allowlist:[...ALLOWLIST].map(([file,reason])=>({file,reason})),
  rules:PATTERNS.map(p=>({id:p.id,why:p.why})),
  // A PASS here means "no violation of these rules", not "no hand-built path
  // is possible". These are the shapes the rules knowingly do not catch, and
  // they are listed so the guarantee is not read as stronger than it is:
  // string concatenation (`root+'/'+STATE_DIRNAME+'/runs'`), a template
  // literal assembling the path, and a constant defined elsewhere and joined
  // in. Each would need real parsing rather than a line regex; the rules cover
  // every shape that has actually occurred in this repository, and the layout
  // unit test covers drift in the one file allowed to hand-build paths.
  known_bypasses:['string concatenation','template literal assembly','a path constant defined in another module'],
  self_check:selfCheckFailures.length?{status:'FAIL',failures:selfCheckFailures}:{status:'PASS',checks:selfCheck.length},
  violations,
  status
};
writeReport(path.join(ROOT,'evals','LAYOUT-BOUNDARY-VALIDATION.json'),report);
console.log(JSON.stringify(report,null,2));
process.exit(status==='FAIL'?1:0);
